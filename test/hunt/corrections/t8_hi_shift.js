const { L, fill, correctDist, correctHub, entryState } = require('/home/claude/test/hunt/corrections/common.js');
(async () => {
  const browser = await L.chromium.launch();
  const page = await L.newPage(browser, 'uCorr8');
  await L.dismiss(page);
  await page.evaluate(() => pbOpenNewRun()); await page.waitForTimeout(300);
  await page.click('#rodToggle button[data-val="engineer"]'); await page.waitForTimeout(150);
  await page.evaluate(() => document.querySelector('#hiToggle button[data-val="stakes"]').click()); await page.waitForTimeout(150);
  await page.evaluate(() => document.querySelector('#startModeToggle button[data-val="stake"]').click()); await page.waitForTimeout(100);
  await fill(page, 'startStakeElev', '104.00'); await page.selectOption('#startCutFill', 'cut'); await fill(page, 'startCutFillVal', '4.00'); await fill(page, 'startStakeReading', '3.00');
  const hub = await page.evaluate(() => { pbAddHub(); const ids = Array.from(document.querySelectorAll('#hubsContainer [data-hub-id]')).map(c => c.dataset.hubId); return ids[ids.length-1]; });
  await fill(page, hub + 'Station', '50');
  await page.evaluate((h) => document.querySelector('#' + h + 'ModeToggle button[data-val="stake"]').click(), hub); await page.waitForTimeout(100);
  await fill(page, hub + 'StakeElev', '105.00'); await page.selectOption('#' + hub + 'CutFill', 'cut'); await fill(page, hub + 'CutFillVal', '5.50'); await fill(page, hub + 'StakeReading', '1.40');
  await fill(page, 'endElevReading', '7.40');
  await page.fill('#totalDist', '100'); await page.fill('#interval', '25'); await page.fill('#runWT', '0.05'); await page.selectOption('#runIdSel', '10');
  await page.waitForTimeout(1200);
  await page.click('text=Review & Calculate'); await page.waitForTimeout(600);
  const rerr = await page.evaluate(() => document.getElementById('inputError').innerText); if (rerr) console.log('review err:', rerr);
  await page.click('button[onclick="pbLock()"]'); await page.waitForSelector('#screen-results.active'); await page.waitForTimeout(600); await L.dismiss(page);
  const id = await page.evaluate(() => window.__debugGetCurrentArchiveEntry().id);
  const endRow = async () => page.evaluate((i) => { const e = window.__debugGetArchive().find(x => x.id === i); const r = e.intervalRows.find(r => r.pointId === 'end'); return { pi: r.piFt, inv: r.inv, hi: e.hi }; }, id);
  let r0 = await endRow();
  console.log('locked end', JSON.stringify(r0));
  L.check('control: HI 106.40 (lowest stake candidate, the hub); End elevation 99.00 from its 7.40 shot', Math.abs(r0.hi - 106.4) < 1e-9 && Math.abs(r0.pi - 99.0) < 1e-9);
  const err = await correctHub(page, hub, 50, 99.45, { wait: 1500 });
  let r1 = await endRow();
  const formEnd = await page.evaluate(() => parseFloat(document.getElementById('endElev').value));
  console.log('after hub corr', err, JSON.stringify(r1), 'form end elev', formEnd);
  L.check('correcting the hub\'s elevation leaves the run\'s HI (106.40) and the End point (elev 99.00, shot 7.40) as recorded', !err && Math.abs(r1.hi - 106.4) < 1e-9 && Math.abs(r1.pi - 99.0) < 1e-9);
  L.check('the live form\'s End elevation still 99.00 after the HI cascade settles', Math.abs(formEnd - 99.0) < 1e-9);
  await correctDist(page, 1, 101, { wait: 1500 });
  const r2 = await endRow();
  console.log('after 2nd corr', JSON.stringify(r2));
  L.check('after an unrelated distance correction the End elevation is still 99.00', Math.abs(r2.pi - 99.0) < 1e-9);
  L.check('no JS errors', page._errors.length === 0);
  await browser.close();
})();
