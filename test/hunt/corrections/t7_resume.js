const { L, fill, correctDist, entryState } = require('/home/claude/test/hunt/corrections/common.js');
(async () => {
  const browser = await L.chromium.launch();
  const uid = 'uCorr7';
  const page = await L.newPage(browser, uid);
  await L.dismiss(page);
  await page.clock.install({ time: Date.now() });
  const idA = await L.lockRun(page, { stats: true }); await L.dismiss(page);
  await page.clock.fastForward(20 * 60000);
  let err = await correctDist(page, 1, 110);
  L.check('control: A corrected to 110', !err && (await entryState(page, idA)).dist === 110);
  await page.evaluate(() => { document.getElementById('endIncompletePanel').style.display = 'none'; pbToggleEndIncomplete(); }); await page.waitForTimeout(100);
  await page.evaluate(() => { const s = document.getElementById('endIncompleteStation'); s.selectedIndex = Array.from(s.options).findIndex(o => o.textContent.trim() === '40.0'); });
  await page.evaluate(() => pbEndRunIncomplete()); await page.waitForTimeout(1200); await L.dismiss(page);
  await page.evaluate((id) => { const i = window.__debugGetArchive().findIndex(e => e.id === id); pbResumeIncompleteRun(i); }, idA); await page.waitForTimeout(600); await L.dismiss(page);
  const td = await page.evaluate(() => document.getElementById('totalDist').value);
  await page.clock.fastForward(10 * 60000);
  await page.click('text=Review & Calculate'); await page.waitForTimeout(600);
  await page.click('button[onclick="pbLock()"]'); await page.waitForSelector('#screen-results.active'); await page.waitForTimeout(800); await L.dismiss(page);
  const idB = await page.evaluate(() => window.__debugGetCurrentArchiveEntry().id);
  await page.clock.fastForward(15 * 60000);
  err = await correctDist(page, 1, 120, { wait: 1500 });
  const sB = await entryState(page, idB);
  let st = await page.evaluate((u) => JSON.parse(localStorage.getItem(u + ':statsLog') || '[]'), uid);
  const hist = await page.evaluate(() => document.getElementById('correctionHistoryWrap').innerText);
  console.log('HIST:', JSON.stringify(hist));
  console.log('resumed form dist', td, 'B', JSON.stringify({ d: sB.dist, c: sB.completed }), JSON.stringify(st.map(x => [x.entryId === idB ? 'B' : x.entryId, x.footage, x.durationMin])));
  L.check('B corrected to 120 ft', !err && sB.dist === 120);
  L.check('Stats: one record (B), 120 ft', st.length === 1 && st[0].entryId === idB && st[0].footage === 120);
  L.check('Correction History on B shows both A\'s (100->110, earlier session) and B\'s (110->120)', /100\.0 → 110\.0/.test(hist) && /110\.0 → 120\.0/.test(hist) && /earlier session/i.test(hist));
  await page.evaluate(() => pbEndRun()); await page.waitForTimeout(1500); await L.dismiss(page);
  st = await page.evaluate((u) => JSON.parse(localStorage.getItem(u + ':statsLog') || '[]'), uid);
  const durs = await page.evaluate(([a, b]) => { const A = window.__debugGetArchive().find(e => e.id === a), B = window.__debugGetArchive().find(e => e.id === b); return [A.durationMin, B.durationMin]; }, [idA, idB]);
  console.log('after End', JSON.stringify(st.map(x => [x.footage, x.durationMin])), durs);
  L.check('after End Run, Stats duration = A + B session times', st.length === 1 && Math.abs(st[0].durationMin - (durs[0] + durs[1])) < 1e-6);
  L.check('no JS errors', page._errors.length === 0);
  await browser.close();
})();
