const { L, fill, entryState } = require('/home/claude/test/hunt/corrections/common.js');
(async () => {
  const browser = await L.chromium.launch();
  const page = await L.newPage(browser, 'uCorr5');
  await L.dismiss(page);
  await page.evaluate(() => pbOpenNewRun()); await page.waitForTimeout(300);
  await page.click('#rodToggle button[data-val="architect"]'); await page.waitForTimeout(200);
  await page.evaluate(() => document.querySelector('#hiToggle button[data-val="direct"]').click()); await page.waitForTimeout(150);
  await fill(page, 'hiDirect_ft', '105'); await fill(page, 'hiDirect_in', '0');
  await fill(page, 'startElev_ft', '100'); await fill(page, 'startElev_in', '0');
  await fill(page, 'endElev_ft', '99'); await fill(page, 'endElev_in', '6');
  const hub = await page.evaluate(() => { pbAddHub(); const ids = Array.from(document.querySelectorAll('#hubsContainer [data-hub-id]')).map(c => c.dataset.hubId); return ids[ids.length-1]; });
  await fill(page, hub + 'Station', '50'); await fill(page, hub + 'Elev_ft', '99'); await fill(page, hub + 'Elev_in', '9');
  await page.fill('#totalDist', '100'); await page.fill('#interval', '25'); await page.fill('#runWT', '0.05'); await page.selectOption('#runIdSel', '10');
  await page.waitForTimeout(900);
  await page.click('text=Review & Calculate'); await page.waitForTimeout(600);
  await page.click('button[onclick="pbLock()"]'); await page.waitForSelector('#screen-results.active'); await page.waitForTimeout(500); await L.dismiss(page);
  const id = await page.evaluate(() => window.__debugGetCurrentArchiveEntry().id);
  const tryHub = async (ft, inch) => {
    await page.evaluate(() => { document.getElementById('correctDistancePanel').style.display = 'none'; pbToggleCorrectDistance(); }); await page.waitForTimeout(100);
    await page.selectOption('#correctDistanceRunSel', 'hub:' + hub); await page.evaluate(() => pbUpdateCorrectDistanceField());
    await page.fill('#correctHubStation', '50'); await fill(page, 'correctHubElev_ft', ft); await fill(page, 'correctHubElev_in', inch);
    await page.evaluate(() => { window._c = pbApplyCorrectDistance(); }); await page.waitForTimeout(900);
    const err = await page.evaluate(() => { const e = document.getElementById('correctDistanceError'); return e.style.display === 'none' ? '' : e.innerText; });
    await L.dismiss(page);
    const s = await entryState(page, id);
    return { err, pi: (s.rows.find(r => r.pid === hub) || {}).pi, corr: s.corr };
  };
  let r = await tryHub('99', '14');
  console.log(JSON.stringify(r));
  L.check('CRITICAL: a hub correction of 99 ft 14 in (Architect\'s Rod) is refused with the inches reason, not saved as 100.167', r.corr === 0 && /inches must be from 0 to 11/.test(r.err));
  r = await tryHub('99', '-3');
  console.log(JSON.stringify(r));
  L.check('a hub correction with -3 in is refused', /inches must be from 0 to 11/.test(r.err));
  r = await tryHub('99', '8');
  console.log(JSON.stringify(r));
  L.check('control: a valid 99 ft 8 in is accepted and saved as 99.667', !r.err && Math.abs(r.pi - (99 + 8/12)) < 1e-9);
  L.check('no JS errors', page._errors.length === 0);
  await browser.close();
})();
