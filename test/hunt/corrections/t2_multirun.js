const { L, fill, correctDist, correctHub, entryState } = require('/home/claude/test/hunt/corrections/common.js');
(async () => {
  const browser = await L.chromium.launch();
  const page = await L.newPage(browser, 'uCorr2');
  await L.dismiss(page);
  await page.evaluate(() => pbOpenNewRun()); await page.waitForTimeout(300);
  await page.click('#rodToggle button[data-val="lenker"]');
  await page.fill('#startElev','100.00'); await page.fill('#endElev','99.00'); await page.fill('#totalDist','100'); await page.fill('#interval','20'); await page.fill('#runWT','0.4'); await page.selectOption('#runIdSel','12');
  await page.check('#saEnableToggle'); await page.fill('#saJobNumber','J-MR'); await page.selectOption('#statsType','PVC Sch 40');
  await page.evaluate(() => pbAddReducerSegment()); await page.waitForTimeout(300);
  await page.fill('#reducerStep','0.2'); await page.fill('#seg2endElev','98.40'); await page.fill('#seg2TotalDist','60'); await page.fill('#seg2Interval','20'); await page.fill('#seg2WT','0.3'); await page.selectOption('#seg2IdSel','8');
  await page.evaluate(() => pbAddSeg(3)); await page.waitForTimeout(300);
  await fill(page, 'seg3Step', '0'); await fill(page, 'seg3endElev', '98.00'); await page.fill('#seg3TotalDist','50'); await page.fill('#seg3Interval','25'); await fill(page, 'seg3WT', '0.3'); await page.selectOption('#seg3IdSel','8');
  const h3 = await page.evaluate(() => { pbAddHubN(3); const ids = Array.from(document.querySelectorAll('#hubsContainer3 [data-hub-id]')).map(c => c.dataset.hubId); return ids[ids.length-1]; });
  await fill(page, h3 + 'Station', '20'); await fill(page, h3 + 'Elev', '98.30'); await fill(page, h3 + 'Label', 'H3');
  await page.waitForTimeout(300);
  await page.click('text=Review & Calculate'); await page.waitForTimeout(600);
  const err0 = await page.evaluate(() => document.getElementById('inputError').innerText);
  if (err0) console.log('review err', err0);
  await page.click('button[onclick="pbLock()"]'); await page.waitForSelector('#screen-results.active'); await page.waitForTimeout(500); await L.dismiss(page);
  const id = await page.evaluate(() => window.__debugGetCurrentArchiveEntry().id);
  let s = await entryState(page, id);
  const pt = (s, pid) => (s.rows.find(r => r.pid === pid) || {});
  console.log('before', s.dist, pt(s, 'seg3start').st, pt(s, h3).st, pt(s, 'seg3end').st);
  L.check('control: 210 ft total, Run 3 starts at 160, hub H3 at 180', s.dist === 210 && pt(s, 'seg3start').st === 160 && pt(s, h3).st === 180);
  const err = await correctDist(page, 2, 70);
  s = await entryState(page, id);
  console.log('after', err, s.dist, pt(s, 'seg3start').st, pt(s, h3).st, pt(s, 'seg3end').st, JSON.stringify(s.rows.map(r => r.st)));
  L.check('Run 2 corrected 60 -> 70: total 220, Run 3 start at 170, H3 at 190, Run 3 end at 220', !err && s.dist === 220 && pt(s, 'seg3start').st === 170 && pt(s, h3).st === 190 && pt(s, 'seg3end').st === 220);
  L.check('Run 3 elevations unchanged (H3 still 98.30, Run 3 end 98.00)', Math.abs(pt(s, h3).pi - 98.3) < 1e-9 && Math.abs(pt(s, 'seg3end').pi - 98.0) < 1e-9);
  const st = await page.evaluate((i) => JSON.parse(localStorage.getItem('uCorr2:statsLog') || '[]').filter(x => x.entryId === i), id);
  console.log(JSON.stringify(st.map(x => [x.footage, x.sizeSegments])));
  L.check('Stats: one record, 220 ft, per run 100 @12" / 70 @8" / 50 @8"', st.length === 1 && st[0].footage === 220 && JSON.stringify(st[0].sizeSegments.map(x => [x.sizeIn, x.footage])) === '[[12,100],[8,70],[8,50]]');
  // hub moved past run end / to station 0
  const e2 = await correctHub(page, h3, 0, 98.25);
  s = await entryState(page, id);
  console.log('hub to 0:', e2, pt(s, h3).st, JSON.stringify(s.rows.filter(r => r.st >= 165 && r.st <= 175)));
  L.check('hub moved to Run 3 station 0: lands at 170 with its own elevation', !e2 && pt(s, h3).st === 170 && Math.abs(pt(s, h3).pi - 98.25) < 1e-9);
  const e3 = await correctHub(page, h3, 50, 98.05);
  s = await entryState(page, id);
  console.log('hub to end:', e3, pt(s, h3).st);
  L.check('hub moved to Run 3 end station 50: lands at 220', !e3 && pt(s, h3).st === 220);
  L.check('no JS errors', page._errors.length === 0);
  await browser.close();
})();
