# Builds, for each migration NN:
#   apply/NN_*.apply.sql   00_guard.sql + the migration: the file to run on live (one transaction)
#   tests/block_tNN.sql    the same + its test, rolled back by the test's own last statement (RESULT: ...)
import os, glob
S = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
guard = open(S + '/00_guard.sql').read()
os.makedirs(S + '/apply', exist_ok=True)
for mig in sorted(glob.glob(S + '/0[1-9]_*.sql')):
    name = os.path.basename(mig); nn = name[:2]
    body = guard + '\n' + open(mig).read()
    open(S + '/apply/' + name.replace('.sql', '.apply.sql'), 'w').write('-- GENERATED by tests/mk.py from 00_guard.sql + ' + name + '. Run as one transaction.\nbegin;\n' + body + '\ncommit;\n')
    t = S + '/tests/t' + nn + '.plpgsql'
    if os.path.exists(t):
        open(S + '/tests/block_t' + nn + '.sql', 'w').write('-- GENERATED by tests/mk.py. Rolled back by its own last statement (RESULT: ...). Changes nothing.\nbegin;\n' + body + '\n' + open(t).read() + '\nrollback;\n')
print('ok')
