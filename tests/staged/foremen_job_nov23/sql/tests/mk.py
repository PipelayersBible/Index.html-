#!/usr/bin/env python3
# Builds from 01_job_foremen.sql:
#   apply/01_job_foremen.apply.sql   begin; + 01 + commit;   (the file to run on live)
#   tests/block_t01.sql              begin; + 01 + t01.plpgsql (always raises RESULT) + rollback;   -> changes nothing
import os
S = os.path.dirname(os.path.abspath(__file__)); Q = os.path.dirname(S)
body = open(Q + '/01_job_foremen.sql').read(); t = open(S + '/t01.plpgsql').read()
os.makedirs(Q + '/apply', exist_ok=True)
open(Q + '/apply/01_job_foremen.apply.sql', 'w').write('-- GENERATED by tests/mk.py from 01_job_foremen.sql. Run as postgres, as one transaction.\nbegin;\n' + body + '\ncommit;\n')
open(S + '/block_t01.sql', 'w').write('-- GENERATED by tests/mk.py. Rolled back by its own last statement (RESULT: ...). Changes nothing.\n'
  '-- Run the whole file as postgres: it applies 01 inside a transaction, tests it as the app (role authenticated + JWT claims)\n'
  '-- and always ends in ERROR: RESULT: n pass, m fail ...; expect 25 pass, 0 fail. Throwaway people and companies roll back with it.\n'
  'begin;\n' + body + '\n' + t + '\nrollback;\n')
print('built apply/01_job_foremen.apply.sql, tests/block_t01.sql')
