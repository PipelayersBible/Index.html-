# mk_sql.py (library_consolidate_nov21): promotion SQL for the trench + 811 consolidation. NOT APPLIED by anything here.
#   python3 tools/mk_sql.py [expected.json]  -> promotion/20_precheck.sql, 21_load.sql, 91_rollback.sql
# Deleting rows renumbers every later ord (the loader pages by ord and needs 0..n-1 with no gap), so the guard is the WHOLE-library md5:
# the load runs only on exactly the live library it was built on (3,270 rows, md5 eb05d565...), and its result must equal the md5 tested on the
# local Postgres copy (expected.json, written by tools/local_test.sh pass 1). The rollback runs only on that tested result and must give back
# eb05d565... exactly.
import json, os, sys
H = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, '/home/claude/index.html-/tests/staged/library_arch_nov20'); sys.path.insert(0, os.path.join(H, 'tools'))
import lib_kb
from build_after import build, RETIRE
V = 'b3e91f6c47d2'
PRE_ALL = 'eb05d565cacc0e0b64a848aa41a5496f'   # server, read 2026-11-21 (SELECT only) = local copy
live, after = build()
N0, N1 = len(live), len(after)
byo = {r['o']: r for r in live}; byid = {r['c']['id']: r for r in live}
exp = json.load(open(sys.argv[1])) if len(sys.argv) > 1 else None
POST_ALL = exp['post_all'] if exp else 'PLACEHOLDER'
SK = '' if exp else '-- pass 1, no expected md5 yet: '
retired = sorted((byid[i] for i in RETIRE), key=lambda r: r['o'])
inplace = [(r['o_old'], byo[r['o_old']], r) for r in after if r['o_old'] is not None and (byo[r['o_old']]['c'] != r['c'] or byo[r['o_old']]['lib'] != r['lib'])]
new = [r for r in after if r['o_old'] is None]
NS = N1 - len(new)   # surviving rows: ords 0..NS-1 after renumbering; new rows NS..N1-1
assert NS == N0 - len(retired) and [r['o'] for r in new] == list(range(NS, N1))
J = lambda v: lib_kb._q(json.dumps(v, ensure_ascii=False))
L = lambda xs: ', '.join("'" + x.replace("'", "''") + "'" for x in xs)
ALLQ = f"(select md5(string_agg(ord||':'||lib||':'||(chunk::text), '|' order by ord)) from pb_ai.kb_chunks where version = '{V}')"
CNT = f"(select count(*) from pb_ai.kb_chunks where version = '{V}')"
counts_tail = f"""  update pb_ai.kb_versions v set n = c.n, counts = c.counts
    from (select sum(k)::int as n, jsonb_object_agg(lib, k) as counts from (select lib, count(*)::int as k from pb_ai.kb_chunks where version = '{V}' group by lib) x) c
   where v.version = '{V}';
  delete from pb_ai.kb_index_parts where version = '{V}';   -- the saved search index is rebuilt by the next cold start (about 2 s, once)
  delete from pb_ai.kb_index where version = '{V}';"""
touched = [(r['o'], r) for r in retired] + [(o, old) for o, old, _ in inplace]
touched_vals = ', '.join(f"({o}, {lib_kb._q(r['c']['id'])}, md5({J(r['c'])}::jsonb::text))" for o, r in sorted(touched, key=lambda x: x[0]))
new_ids = [r['c']['id'] for r in new]

pre = f"""-- 20_precheck.sql (library_consolidate_nov21): SELECT only. Run before and after 21_load.sql.
-- BEFORE: rows {N0}, max_ord {N0 - 1}, kb_n {N0}, all_md5 {PRE_ALL}, touched_ok {len(touched)} (the {len(retired)} rows deleted + {len(inplace)} changed in place, by ord, id and text), new_ids_there 0.
-- AFTER:  rows {N1}, max_ord {N1 - 1}, kb_n {N1}, all_md5 {POST_ALL}, touched_ok 0 (or a few by chance of ord), new_ids_there {len(new)}.
-- If all_md5 differs BEFORE, the live library changed since this package was built (2026-11-21): do not run 21 (it would refuse anyway); rebuild the package.
select {CNT} as rows,
       (select max(ord) from pb_ai.kb_chunks where version = '{V}') as max_ord,
       (select n from pb_ai.kb_versions where version = '{V}' and active) as kb_n,
       {ALLQ} as all_md5,
       (select count(*) from pb_ai.kb_chunks k join (values {touched_vals}) t(o, id, m) on k.ord = t.o and k.chunk->>'id' = t.id and md5(k.chunk::text) = t.m where k.version = '{V}') as touched_ok,
       (select count(*) from pb_ai.kb_chunks where version = '{V}' and chunk->>'id' in ({L(new_ids)})) as new_ids_there;
"""

upd = []
for o, old, nr in inplace:
    upd.append(f"""  -- ord {o}: {old['c']['id']}{' -> ' + nr['c']['id'] if nr['c']['id'] != old['c']['id'] else ' (edited in place)'}
  update pb_ai.kb_chunks set lib = '{nr['lib']}', chunk = {J(nr['c'])}::jsonb
   where version = '{V}' and ord = {o} and chunk->>'id' = {lib_kb._q(old['c']['id'])} and md5(chunk::text) = md5({J(old['c'])}::jsonb::text);
  get diagnostics vk = row_count; if vk <> 1 then raise exception 'FAIL: row % is not the expected live text', {o}; end if;""")
del_vals = ', '.join(f"({r['o']}, {lib_kb._q(r['c']['id'])})" for r in retired)
rows_ins = ',\n'.join(json.dumps({'lib': r['lib'], 'chunk': r['c']}, ensure_ascii=False) for r in new)
load = f"""-- 21_load.sql (library_consolidate_nov21): trench + 811 consolidation of the Ask library, ONE transaction. NOT APPLIED. Generated by tools/mk_sql.py.
-- {N0} -> {N1} rows: deletes {len(retired)} retired cards, changes {len(inplace)} rows in place (same ord), renumbers the survivors 0..{NS - 1} (no gap, same order),
-- adds {len(new)} cards at ord {NS}..{N1 - 1}, fixes kb_versions.n and drops the saved search index.
-- Guarded by the whole-library md5: runs only on {N0} rows with md5 {PRE_ALL}. Run twice: the second run says "already applied".
begin;
lock table pb_ai.kb_chunks in share row exclusive mode;
do $load$
declare vk int; vn int; vmx int; vd int; vm text;
begin
  select {CNT}, {ALLQ} into vn, vm;
  {SK}if vn = {N1} and vm = '{POST_ALL}' then raise notice 'consolidate 21_load: already applied, nothing changed'; return; end if;
  if vn <> {N0} or vm is distinct from '{PRE_ALL}' then raise exception 'FAIL: library is not the live state this was built on (% rows, md5 %)', vn, vm; end if;
  if (select n from pb_ai.kb_versions where version = '{V}' and active) is distinct from {N0} then raise exception 'FAIL: kb_versions.n is not {N0} or {V} is not active'; end if;

  -- 1. rows changed in place
{chr(10).join(upd)}

  -- 2. the retired cards (facts moved: see work/factmap.tsv)
  delete from pb_ai.kb_chunks k using (values {del_vals}) t(o, id) where k.version = '{V}' and k.ord = t.o and k.chunk->>'id' = t.id;
  get diagnostics vk = row_count; if vk <> {len(retired)} then raise exception 'FAIL: deleted % rows, expected {len(retired)}', vk; end if;

  -- 3. renumber the survivors 0..{NS - 1} in the same order (through negative ords, so the primary key never clashes)
  update pb_ai.kb_chunks set ord = -1 - ord where version = '{V}';
  update pb_ai.kb_chunks k set ord = m.n from (select ord as neg, (row_number() over (order by ord desc) - 1)::int as n from pb_ai.kb_chunks where version = '{V}') m
   where k.version = '{V}' and k.ord = m.neg;
  get diagnostics vk = row_count; if vk <> {NS} then raise exception 'FAIL: renumbered % rows, expected {NS}', vk; end if;

  -- 4. new cards
  insert into pb_ai.kb_chunks (version, ord, lib, chunk)
  select '{V}', {NS - 1} + t.i, t.e->>'lib', t.e->'chunk' from jsonb_array_elements({lib_kb._q('[' + rows_ins + ']')}::jsonb) with ordinality t(e, i);
  get diagnostics vk = row_count; if vk <> {len(new)} then raise exception 'FAIL: inserted % rows', vk; end if;

  -- 5. row count for the loader, drop the saved index
{counts_tail}

  -- 6. checks
  select count(*), max(ord), count(distinct chunk->>'id') into vn, vmx, vd from pb_ai.kb_chunks where version = '{V}';
  if vn <> {N1} or vmx <> {N1 - 1} then raise exception 'FAIL ord gap or count: % rows, max ord %', vn, vmx; end if;
  if vd <> vn then raise exception 'FAIL duplicate chunk id'; end if;
  if (select v.n from pb_ai.kb_versions v where v.version = '{V}') <> {N1} then raise exception 'FAIL kb_versions.n'; end if;
  {SK}if {ALLQ} <> '{POST_ALL}' then raise exception 'FAIL: result differs from the tested library'; end if;
  raise notice 'consolidate 21_load: applied, % rows', vn;
end $load$;
commit;
"""

back_inplace = json.dumps([[o, old['lib'], old['c']] for o, old, _ in inplace], ensure_ascii=False)
back_retired = json.dumps([[r['o'], r['lib'], r['c']] for r in retired], ensure_ascii=False)
assert '$kb$' not in back_inplace + back_retired
ret_ords = ','.join(str(r['o']) for r in retired)
rb = f"""-- 91_rollback.sql (library_consolidate_nov21): undo 21_load.sql exactly. NOT APPLIED. Generated by tools/mk_sql.py.
-- Deletes the {len(new)} new cards, puts the survivors back on their old ords, restores the {len(inplace)} rows changed in place and re-inserts the {len(retired)}
-- retired cards at their old ords (content from the live copy, md5 {PRE_ALL}), fixes kb_versions.n, drops the saved index.
-- Guarded: runs only on the tested result of 21 (md5 {POST_ALL}); must end at {N0} rows, md5 {PRE_ALL}. Run twice: "already rolled back".
begin;
lock table pb_ai.kb_chunks in share row exclusive mode;
do $rb$
declare vk int; vn int; vm text;
begin
  select {CNT}, {ALLQ} into vn, vm;
  if vn = {N0} and vm = '{PRE_ALL}' then raise notice 'consolidate 91_rollback: already rolled back (or never applied), nothing changed'; return; end if;
  if vn <> {N1} or vm is distinct from '{POST_ALL}' then raise exception 'FAIL: the library is not in the state 21_load.sql leaves (% rows, md5 %): nothing rolled back', vn, vm; end if;
  delete from pb_ai.kb_chunks where version = '{V}' and ord >= {NS} and chunk->>'id' in ({L(new_ids)});
  get diagnostics vk = row_count; if vk <> {len(new)} then raise exception 'FAIL: % new rows deleted', vk; end if;
  update pb_ai.kb_chunks set ord = -1 - ord where version = '{V}';
  update pb_ai.kb_chunks k set ord = m.o from (select o, (row_number() over (order by o) - 1)::int as n from generate_series(0, {N0 - 1}) o where o <> all(array[{ret_ords}])) m
   where k.version = '{V}' and k.ord = -1 - m.n;
  get diagnostics vk = row_count; if vk <> {NS} then raise exception 'FAIL: % rows moved back', vk; end if;
  update pb_ai.kb_chunks k set lib = e->>1, chunk = e->2 from jsonb_array_elements({lib_kb._q(back_inplace)}::jsonb) e where k.version = '{V}' and k.ord = (e->>0)::int;
  get diagnostics vk = row_count; if vk <> {len(inplace)} then raise exception 'FAIL: % rows put back', vk; end if;
  insert into pb_ai.kb_chunks (version, ord, lib, chunk) select '{V}', (e->>0)::int, e->>1, e->2 from jsonb_array_elements({lib_kb._q(back_retired)}::jsonb) e;
  get diagnostics vk = row_count; if vk <> {len(retired)} then raise exception 'FAIL: % retired rows re-inserted', vk; end if;
{counts_tail}
  if {CNT} <> {N0} or (select max(ord) from pb_ai.kb_chunks where version = '{V}') <> {N0 - 1} then raise exception 'FAIL: row count / ords'; end if;
  if {ALLQ} <> '{PRE_ALL}' then raise exception 'FAIL: not back to the live library md5'; end if;
  if (select v.n from pb_ai.kb_versions v where v.version = '{V}') <> {N0} then raise exception 'FAIL kb_versions.n'; end if;
  raise notice 'consolidate 91_rollback: done, % rows', {N0};
end $rb$;
commit;
"""
os.makedirs(os.path.join(H, 'promotion'), exist_ok=True)
for fn, s in (('20_precheck.sql', pre), ('21_load.sql', load), ('91_rollback.sql', rb)):
    assert len(s.encode()) < 900_000, fn
    open(os.path.join(H, 'promotion', fn), 'w').write(s)
json.dump({'n0': N0, 'n1': N1, 'ns': NS, 'retired_ords': [r['o'] for r in retired], 'inplace_ords': [o for o, _, _ in inplace], 'new_ids': new_ids}, open(os.path.join(H, 'work/sql_meta.json'), 'w'), indent=1)
print(f'{N0} -> {N1}: delete {len(retired)}, in place {len(inplace)}, new {len(new)}; expected md5 ' + (POST_ALL if exp else 'PLACEHOLDER (run tools/local_test.sh)'))
for fn in ('20_precheck.sql', '21_load.sql', '91_rollback.sql'): print(fn, os.path.getsize(os.path.join(H, 'promotion', fn)), 'bytes')
