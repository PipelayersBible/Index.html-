#!/usr/bin/env python3
"""Builds strings_es.json (the strings file), safety_review.md and the dictionary the engine carries.
Source of truth for the Spanish: strings_src.py (S / P calls grouped by SCREEN). Run: python3 build.py"""
import json, re, sys, os, collections
HERE = os.path.dirname(os.path.abspath(__file__))
ENT = []; cur = {'screen': ''}
def SCREEN(name): cur['screen'] = name
def S(en, es, safety=0, ctx='', note=''): ENT.append(dict(kind='s', screen=cur['screen'], en=en, es=es, safety=int(bool(safety)), ctx=ctx, note=note))
def P(en, es, safety=0, ctx='', note=''): ENT.append(dict(kind='p', screen=cur['screen'], en=en, es=es, safety=int(bool(safety)), ctx=ctx, note=note))
exec(compile(open(os.path.join(HERE, 'strings_src.py'), encoding='utf-8').read(), 'strings_src.py', 'exec'))
norm = lambda s: re.sub(r'[ \t\r\n\f\v ]+', lambda m: ' ' if ' ' not in m.group(0) else m.group(0), s).strip()
def normk(s): return re.sub(r'[ \t\r\n\f\v]+', ' ', s).strip()   # same as the engine's /\s+/ except it keeps NBSP out of this (JS \s includes NBSP)
def jsnorm(s): return re.sub(r'\s+', ' ', s).strip()             # Python \s on str covers NBSP too, like JS
errs = []; T = collections.OrderedDict(); PAT = []; ids = collections.Counter(); out = []
tagseq = lambda s: re.findall(r'<(\d+)(/?)>', s)
for e in ENT:
    ids[e['screen']] += 1; e['id'] = '%s.%03d' % (e['screen'], ids[e['screen']])
    en = jsnorm(e['en']); es = e['es'].strip()
    if tagseq(en) != tagseq(es): errs.append('%s: tags differ: %r' % (e['id'], en[:60]))
    if e['kind'] == 's':
        if '{' in en and re.search(r'\{\d', en): errs.append('%s: placeholder in a plain string (use P): %r' % (e['id'], en[:60]))
        slot = T.setdefault(en, [])
        if any(c == e['ctx'] for c, _ in slot):
            if dict(slot)[e['ctx']] != es: errs.append('%s: same English, different Spanish, same ctx: %r' % (e['id'], en[:60]))
            e['dup'] = 1
        else: slot.append((e['ctx'], es))
    else:
        ph_en = re.findall(r'\{(\d)(?::[a-z])?\}', en); ph_es = re.findall(r'\{(\d)(?::t)?\}', es)
        if ph_en != [str(i) for i in range(len(ph_en))]: errs.append('%s: placeholders must be {0},{1}.. in order: %r' % (e['id'], en[:60]))
        if not set(ph_es) <= set(ph_en): errs.append('%s: Spanish uses a placeholder the English lacks: %r' % (e['id'], en[:60]))
        rx = ''; pos = 0
        for m in re.finditer(r'\{(\d)(?::([a-z]))?\}', en):
            rx += re.escape(en[pos:m.start()]).replace('\\ ', ' ')
            rx += {'d': r'([-+]?[\d.,:/+]+)', 'w': r'(\S+)', None: r'(.+?)', 'a': r'(.*)'}[m.group(2)]; pos = m.end()
        rx += re.escape(en[pos:]).replace('\\ ', ' ')
        PAT.append(['^' + rx + '$', es] + ([e['ctx']] if e['ctx'] else []))
    out.append(e)
Tj = collections.OrderedDict()
for en, slot in T.items():
    if len(slot) == 1 and slot[0][0] == '': Tj[en] = slot[0][1]
    else:
        ctxd = [[c, s] for c, s in slot if c]; dflt = [s for c, s in slot if not c]
        Tj[en] = ctxd + dflt
if errs:
    print('\n'.join('ERR ' + x for x in errs)); sys.exit(1)
dict_js = json.dumps({'t': Tj, 'p': PAT}, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/')
open(os.path.join(HERE, 'dict.json'), 'w', encoding='utf-8').write(dict_js)
strings = [collections.OrderedDict([('id', e['id']), ('screen', e['screen']), ('type', 'pattern' if e['kind'] == 'p' else 'text'), ('safety', bool(e['safety'])), ('en', jsnorm(e['en'])), ('es', e['es'].strip())] + ([('only_inside', e['ctx'])] if e['ctx'] else []) + ([('note', e['note'])] if e['note'] else [])) for e in out if not e.get('dup')]
meta = collections.OrderedDict([('what', "Spanish strings for The Pipelayer's Bible, phase 1. Generated by build.py from strings_src.py; edit strings_src.py."),
    ('key', 'The English text is the key. <1>..</1> marks a bold word / link inside the sentence (keep the numbers and their order). {0} {1} are values the app fills in.'),
    ('safety', 'safety: true = safety-critical wording. A fluent person in the trade reviews these first (see safety_review.md).'),
    ('count', len(strings)), ('safety_count', sum(1 for s in strings if s['safety']))])
json.dump(collections.OrderedDict([('meta', meta), ('strings', strings)]), open(os.path.join(HERE, 'strings_es.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
with open(os.path.join(HERE, 'safety_review.md'), 'w', encoding='utf-8') as f:
    f.write('# Safety-critical Spanish strings: review these first\n\nEvery string below is shown on a confined space, air test, trench or emergency screen. A fluent Spanish speaker who works in the trade should read each one against the English before Spanish is turned on for real crews. Generated by build.py.\n\n')
    last = None
    for s in strings:
        if not s['safety']: continue
        if s['screen'] != last: f.write('\n## %s\n\n' % s['screen']); last = s['screen']
        f.write('- **%s**\n  - EN: %s\n  - ES: %s\n' % (s['id'], s['en'].replace('\n', ' / '), s['es'].replace('\n', ' / ')))
by = collections.Counter(s['screen'] for s in strings)
print('strings: %d (safety %d), patterns %d, dict %d bytes' % (len(strings), meta['safety_count'], len(PAT), len(dict_js.encode())))
print('by screen:', dict(by))
