#!/usr/bin/env python3
# Builds ../block_tNN.sql (NN = 01..05) from the apply files and src/tNN.plpgsql.
# Each block is ONE statement (a DO block): helpers, then apply 01..NN (so it works before or after the earlier items are
# applied: every apply file is safe to run twice), then the test, then (where the test says) the undo, and it ALWAYS
# ends with raise exception 'RESULT: n pass, m fail ...' so nothing is kept.
# Markers in tNN.plpgsql: --@DECL / --@BODY sections; in the body --@FIXTURES, --@SMOKE, --@APPLY:NN, --@UNDO:NN.
import os, re, glob, hashlib
S = os.path.dirname(os.path.abspath(__file__)); L = os.path.dirname(S)
rd = lambda p: open(p).read()
apply_ = {os.path.basename(p)[:2]: rd(p) for p in glob.glob(L + '/0[1-5]_*.apply.sql')}
undo = {os.path.basename(p)[8:10]: rd(p) for p in glob.glob(L + '/99_undo_0[1-5].sql')}
for k, v in list(apply_.items()) + list(undo.items()):
    assert '$T$' not in v and '$q$' not in v, k
    top = re.sub(r'(?s)(\$\w*\$).*?\1', '', re.sub(r'--[^\n]*', '', v))  # outside dollar-quoted bodies and comments
    assert not re.search(r'(?im)^\s*(begin|commit|rollback)\s*;', top), k
    for st in top.split(';'):  # a top-level query is not valid inside a DO block
        assert not re.match(r'(?i)\s*(select|with|values|table)\s', st), (k, st[:80])
decl, pre, fx, smoke, tally = (rd(f'{S}/_{n}.plpgsql') for n in ('decl', 'prelude', 'fixtures', 'smoke', 'tally'))
TITLE = {'01': '01 pb_stage helper', '02': '02 B3 open permit first-seen proof', '03': '03 B9 audit + no-change guards (7 tables)',
         '04': '04 B5 toolbox talk versions', '05': '05 B8 run history export (manager-only)'}
for nn in ['01', '02', '03', '04', '05']:
    t = rd(f'{S}/t{nn}.plpgsql')
    tdecl, body = t.split('--@BODY\n', 1); tdecl = tdecl.replace('--@DECL\n', '')
    body = body.replace('--@FIXTURES\n', fx).replace('--@SMOKE\n', smoke)
    body = re.sub(r'--@APPLY:(\d\d)\n', lambda m: f'  -- ===== apply {m.group(1)} (again) =====\n' + apply_[m.group(1)] + '\n', body)
    body = re.sub(r'--@UNDO:(\d\d)\n', lambda m: f'  -- ===== undo {m.group(1)} =====\n' + undo[m.group(1)] + '\n', body)
    applies = ''.join(f'  -- ===== apply {k} =====\n' + apply_[k] + '\n' for k in sorted(apply_) if k <= nn)
    out = (f'-- GENERATED by src/mk.py. records_nov22 Phase B test {TITLE[nn]}.\n'
           '-- ONE statement (a DO block). Runs apply 01..' + nn + ' (each safe to run twice), exercises it, then ALWAYS raises\n'
           "-- 'RESULT: n pass, m fail ...' so the whole block is rolled back and NOTHING is kept (throwaway users/company included).\n"
           '-- Expect an ERROR whose message starts with RESULT: and says 0 fail.\n'
           'do $T$\ndeclare\n' + decl + tdecl + 'begin\n' + pre + applies + body + tally + 'end $T$;\n')
    open(f'{L}/block_t{nn}.sql', 'w').write(out)
print('built', ' '.join(f'block_t{n}.sql' for n in ['01', '02', '03', '04', '05']))
