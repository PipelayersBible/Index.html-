# mk_rollback.py: promotion/94_library_rollback.sql = undo 04_library_core.sql. Every row 04 changes in place (ord < 2840 in out/rows_changed.jsonl) goes back to its
# live content from ask_state_nov20/work/kb_after.json (the copy the set was built on; those ords are unchanged on live, checked by tools/local_sql_test.sh md5), rows >= 2840 are deleted.
import json, os
H = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); S = os.path.dirname(H)
live = json.load(open(os.path.join(S, 'ask_state_nov20/work/kb_after.json')))
by_ord = {int(c['_ord']): (lib, {k: v for k, v in c.items() if k != '_ord'}) for lib, v in live.items() for c in v}
n_live = len(by_ord)
rows = [json.loads(l) for l in open(os.path.join(H, 'out/rows_changed.jsonl'))]
back = [[r['ord'], by_ord[r['ord']][0], by_ord[r['ord']][1]] for r in rows if r['ord'] < n_live]
arr = json.dumps(back, ensure_ascii=False); assert '$kb$' not in arr
sql = f"""-- 94_library_rollback.sql: undo 04_library_core.sql. Puts the {len(back)} rows changed in place back to their Nov 20 live content (by ord, from ask_state_nov20/work/kb_after.json,
-- the copy the set was built on) and deletes the rows added at ord {n_live} and up. Then the row count and the saved index, as in 04. Generated by tools/mk_rollback.py.
begin;
lock table pb_ai.kb_chunks in share row exclusive mode;
update pb_ai.kb_chunks k set lib = e->>1, chunk = e->2 from jsonb_array_elements($kb${arr}$kb$::jsonb) e where k.version = 'b3e91f6c47d2' and k.ord = (e->>0)::int;
delete from pb_ai.kb_chunks where version = 'b3e91f6c47d2' and ord >= {n_live};
update pb_ai.kb_versions v set n = c.n, counts = c.counts from (select sum(k)::int as n, jsonb_object_agg(lib, k) as counts from (select lib, count(*)::int as k from pb_ai.kb_chunks where version = 'b3e91f6c47d2' group by lib) x) c where v.version = 'b3e91f6c47d2';
delete from pb_ai.kb_index_parts where version = 'b3e91f6c47d2';
delete from pb_ai.kb_index where version = 'b3e91f6c47d2';
do $chk$ begin if (select count(*) from pb_ai.kb_chunks where version = 'b3e91f6c47d2') <> {n_live} then raise exception 'FAIL: rows <> {n_live}'; end if; end $chk$;
commit;
"""
open(os.path.join(H, 'promotion/94_library_rollback.sql'), 'w').write(sql)
print(f'94: {len(back)} rows back, delete ord >= {n_live}')
