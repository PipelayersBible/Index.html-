# mk_overlay.py <rev>: out/rows_changed.jsonl -> src_patch/kb_overlay.ts (the staged library as an in-memory overlay for the TEST function)
import json, os, sys
H = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); S = os.path.dirname(H)
live = json.load(open(os.path.join(S, 'ask_state_nov20/work/kb_live2.json')))
by_ord = {int(c['_ord']): c['id'] for v in live.values() for c in v}
rep, add = {}, []
for l in open(os.path.join(H, 'out/rows_changed.jsonl')):
    r = json.loads(l); e = {'lib': r['lib'], 'chunk': r['chunk']}
    if r['ord'] in by_ord: rep[by_ord[r['ord']]] = e
    else: add.append(e)
o = {'rev': sys.argv[1], 'base': 'b3e91f6c47d2', 'replace': rep, 'add': add}
open(os.path.join(H, 'src_patch/kb_overlay.ts'), 'w').write('// generated by tools/mk_overlay.py: the staged library, laid over the live rows on the test function only\nexport const OVERLAY = ' + json.dumps(o, ensure_ascii=False) + ';\n')
print(f'overlay {sys.argv[1]}: {len(rep)} replaced, {len(add)} added, {os.path.getsize(os.path.join(H, "src_patch/kb_overlay.ts"))} bytes')
