#!/usr/bin/env python3
# ask_state_nov20: generates sql/01_ask_kb_state_fix.sql (NOT APPLIED) and work/kb_after.json (local copy with the fix, for the eval).
# What it does, all guarded (each update touches a row only if it still holds the text this file expects):
#   A. explicit `state` on the chunks whose state is not in their id, topic or title
#   B. puts the full source line back on the chunks whose source was shortened on Nov 20 only to get past the old filter
#   C. content: titles of the three "not confirmed" 811 chunks say what the others say; Arizona's chunk knows "Blue Stake"
# Apply ONLY AFTER the ask_state build is live: with the old build, step B hides those chunks again in 49 states.
import json, os
H = os.path.dirname(os.path.abspath(__file__)); N = '/home/claude/index.html-/tests/staged/ask_nationwide_nov20/'
V = 'b3e91f6c47d2'
old = json.load(open(N + 'work/kb_live.json')); ed = json.load(open(N + 'work/edited_chunks.json'))
kb = json.load(open(H + '/../work/kb_live2.json'))
by_old = {str(c['_ord']): c for l in old for c in old[l]}
cur = {c['id']: c for l in kb for c in kb[l]}
q = lambda t, tag='s': '$%s$%s$%s$' % (tag, t, tag)
out = ['-- 01_ask_kb_state_fix.sql (ask_state_nov20, 2026-11-20). NOT APPLIED. Generated by gen_kb_fix.py.',
       '-- APPLY ONLY AFTER the ask_state Ask build is live (the new filter reads the chunk\'s own state, not its source line).',
       '-- With the old build still live, part B would hide these safety chunks again outside one state.',
       '-- Expect: every update = 1 row. The last select shows the counts. No rows added or removed.', '', 'begin;', '']
# A. explicit state
TAGS = {'rsf-1': 'CA', 'rsf-2': 'CA'}
out.append('-- A. explicit state: Greenbook-based trench repair chunks are California (their topic and title do not say so)')
for i, st in TAGS.items():
    assert i in cur and 'Greenbook' in cur[i]['source'], i
    out.append("update pb_ai.kb_chunks set chunk = chunk || jsonb_build_object('state', '%s') where version = '%s' and chunk->>'id' = '%s' and not (chunk ? 'state');" % (st, V, i))
    cur[i]['state'] = st
# B. sources back
out += ['', '-- B. full source lines back (shortened on Nov 20 only so the old filter would not hide the chunk)']
nB = 0
for o, e in sorted(ed.items(), key=lambda x: int(x[0])):
    c = by_old[o]
    if (c.get('source') or '') == (e.get('source') or ''): continue
    i = e['id']; assert cur[i]['source'] == e['source'], i
    out.append("update pb_ai.kb_chunks set chunk = jsonb_set(chunk, '{source}', to_jsonb(%s::text)) where version = '%s' and ord = %s and chunk->>'id' = '%s' and chunk->>'source' = %s;" % (q(c['source']), V, o, i, q(e['source'])))
    cur[i]['source'] = c['source']; nB += 1
# C. content
out += ['', '-- C. content. Titles: the 811 chunks of the three states with no confirmed numbers now carry the same words as the other 48,',
        '--    so "how long is a ticket good for" finds them (it ranked 65th; checked with tools/evalret.mjs).']
for st, name in (('ar', 'Arkansas'), ('la', 'Louisiana'), ('mt', 'Montana')):
    i = 'dig-' + st; t0 = cur[i]['title']; assert t0 == '%s 811 dig rules: 811 center and what to check (%s 811)' % (name, name), t0
    t1 = '%s 811 dig rules: wait before digging, ticket life, tolerance zone are not confirmed, what to check (%s 811)' % (name, name)
    out.append("update pb_ai.kb_chunks set chunk = jsonb_set(chunk, '{title}', to_jsonb(%s::text)) where version = '%s' and chunk->>'id' = '%s' and chunk->>'title' = %s;" % (q(t1), V, i, q(t0)))
    cur[i]['title'] = t1
out.append('--    Arizona: crews call locates "blue stake" (Arizona 811 was Arizona Blue Stake: queencreekaz.gov/government/utilities/water/arizona-811).')
a0 = 'Call 811 or go online: Arizona 811 (arizona811.com).'; a1 = 'Call 811 or go online: Arizona 811 (arizona811.com), formerly Arizona Blue Stake; crews still say "blue stake" for a locate ticket and "blue stake marks" for locate marks.'
assert cur['dig-az']['text'].count(a0) == 1
out.append("update pb_ai.kb_chunks set chunk = jsonb_set(chunk, '{text}', to_jsonb(replace(chunk->>'text', %s, %s))) where version = '%s' and chunk->>'id' = 'dig-az' and strpos(chunk->>'text', %s) > 0 and strpos(chunk->>'text', 'Blue Stake') = 0;" % (q(a0), q(a1), V, q(a0)))
cur['dig-az']['text'] = cur['dig-az']['text'].replace(a0, a1)
t0 = cur['dig-az']['title']; t1 = t0.replace('(Arizona 811)', '(Arizona 811, Blue Stake)'); assert t0 != t1
out.append("update pb_ai.kb_chunks set chunk = jsonb_set(chunk, '{title}', to_jsonb(%s::text)) where version = '%s' and chunk->>'id' = 'dig-az' and chunk->>'title' = %s;" % (q(t1), V, q(t0)))
cur['dig-az']['title'] = t1
u0 = 'Call 811 or go online: Blue Stakes of Utah 811 (bluestakes.org).'; u1 = 'Call 811 or go online: Blue Stakes of Utah 811 (bluestakes.org); crews say "blue stake" for a locate ticket and "blue stake marks" for locate marks.'
assert cur['dig-ut']['text'].count(u0) == 1
out.append("update pb_ai.kb_chunks set chunk = jsonb_set(chunk, '{text}', to_jsonb(replace(chunk->>'text', %s, %s))) where version = '%s' and chunk->>'id' = 'dig-ut' and strpos(chunk->>'text', %s) > 0 and strpos(chunk->>'text', 'blue stake marks') = 0;" % (q(u0), q(u1), V, q(u0)))
cur['dig-ut']['text'] = cur['dig-ut']['text'].replace(u0, u1)
out += ['', '-- the saved search index is rebuilt by the next Ask worker that starts (same reset as 01_ask_kb_nationwide.sql)',
        "update pb_ai.kb_index set parts = 32 where version = '%s';" % V, '',
        "select (select count(*) from pb_ai.kb_chunks where version = '%s' and chunk ? 'state') as state_tags, -- expect %d" % (V, len(TAGS)),
        "       (select count(*) from pb_ai.kb_chunks where version = '%s' and chunk->>'source' like '%%Florida DOH%%') as florida_sources_back, -- expect 3" % V,
        "       (select count(*) from pb_ai.kb_chunks where version = '%s' and chunk->>'id' in ('dig-ar','dig-la','dig-mt') and chunk->>'title' like '%%ticket life%%') as titles, -- expect 3" % V,
        "       (select count(*) from pb_ai.kb_chunks where version = '%s') as rows, (select n from pb_ai.kb_versions where version = '%s') as n; -- equal" % (V, V),
        '', 'commit;', '-- Warm Ask workers keep their in-memory index; the edits reach answers as workers cold-start.', '']
open(H + '/01_ask_kb_state_fix.sql', 'w').write('\n'.join(out))
json.dump(kb, open(H + '/../work/kb_after.json', 'w'))
print('A tags', len(TAGS), '| B sources back', nB, '| C content 6 updates')
