# Builds, for each migration NN (01, 02, 03):
#   apply/NN_*.apply.sql   the migration in one transaction: the file to run on live
#   tests/block_tNN.sql    migrations 01..NN + test NN, rolled back by the test's own last statement (RESULT: ...)
import os, glob
S = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.makedirs(S + '/apply', exist_ok=True)
migs = sorted(glob.glob(S + '/0[1-9]_*.sql'))
for i, mig in enumerate(migs):
    name = os.path.basename(mig); nn = name[:2]
    body = open(mig).read()
    open(S + '/apply/' + name.replace('.sql', '.apply.sql'), 'w').write('-- GENERATED by tests/mk.py from ' + name + '. Run as one transaction.\nbegin;\n' + body + '\ncommit;\n')
    t = S + '/tests/t' + nn + '.plpgsql'
    if os.path.exists(t):
        pre = ''.join('\n-- ==== ' + os.path.basename(m) + ' ====\n' + open(m).read() for m in migs[:i + 1])
        open(S + '/tests/block_t' + nn + '.sql', 'w').write('-- GENERATED by tests/mk.py. Rolled back by its own last statement (RESULT: ...). Changes nothing.\n'
            '-- Contains migrations 01..' + nn + ' (each safe to run twice) and test ' + nn + '.\nbegin;\n' + pre + '\n' + open(t).read() + '\nrollback;\n')
print('ok')
