# Eval cases (.jsonl, LIBRARY_RULES.md section 5) -> SQL for pb_ai.eval_set. NOT applied. Needs sql/PROPOSED_eval_style.sql first.
#   python3 tools/cases_sql.py cases.jsonl [more.jsonl ...] > sql/eval_cases_<name>.sql
# state_strict cases get one more mustnot: the name of any other state (so an answer that brings up another state fails).
import json, sys, os, re
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
import lib_kb
rows, seen = [], set()
for f in sys.argv[1:]:
    for c in lib_kb.load_jsonl(f):
        e = lib_kb.check_case(c)
        if e or c['id'] in seen: sys.exit(f"{c.get('id')}: {e or 'duplicate id'}")
        seen.add(c['id'])
        st = c['where'][-2:]; mustnot = list(c.get('mustnot', []))
        if c.get('state_strict'):
            named = lib_kb.state_names_in(c['q'])
            others = [n for k, n in lib_kb.STATES.items() if k != st and k not in named and not (st == 'WV' and k == 'VA') and k != 'DC']
            own = lib_kb.STATES[st]
            # "Washington" also appears in "Washington, DC"; "Virginia" inside "West Virginia" is handled by the lookbehind
            mustnot.append(r'\m(' + '|'.join(('(?<!West )Virginia' if n == 'Virginia' else n) for n in others if n not in own) + r')\M')
        q = lambda s: "'" + s.replace("'", "''") + "'"
        j = lambda v: q(json.dumps(v)) + '::jsonb'
        rows.append(f"({q(c['id'])}, {q(c['cat'])}, {q(c['q'])}, {q(c['where'])}, {q(c.get('level', 'pipelayer'))}, {j(c['must'])}, {j(mustnot)}, "
                    f"{c.get('maxwords', lib_kb.CASE_MAXWORDS[c['kind']])}, true, {j(c['lead'])}, {'true' if c.get('complex') else 'false'})")
print(f"-- {len(rows)} library eval cases. NOT APPLIED. Generated by tools/cases_sql.py. Run sql/PROPOSED_eval_style.sql first (adds lead, complex).")
print('insert into pb_ai.eval_set (id, cat, q, "where", level, must, mustnot, maxwords, active, lead, complex) values\n' + ',\n'.join(rows) + '\non conflict (id) do nothing;')
