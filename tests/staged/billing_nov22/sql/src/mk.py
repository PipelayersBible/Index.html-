#!/usr/bin/env python3
# Builds ../block_t01.sql: ONE DO statement = test helpers + fixtures + apply 01 + checks + undo 01 + apply 01 again,
# ALWAYS ending in raise exception 'RESULT: n pass, m fail ...' so nothing is kept. Markers: --@DECL, --@BODY, --@APPLY:01, --@UNDO:01.
import os, re
S = os.path.dirname(os.path.abspath(__file__)); L = os.path.dirname(S)
rd = lambda p: open(p).read()
ap, un = rd(L + '/01_billing.apply.sql'), rd(L + '/99_undo_01.sql')
for k, v in (('apply', ap), ('undo', un)):
    assert '$T$' not in v and '$q$' not in v, k
    top = re.sub(r'(?s)(\$\w*\$).*?\1', '', re.sub(r'--[^\n]*', '', v))
    assert not re.search(r'(?im)^\s*(begin|commit|rollback)\s*;', top), k
    for st in top.split(';'):
        assert not re.match(r'(?i)\s*(select|with|values|table)\s', st), (k, st[:80])
t = rd(S + '/t01.plpgsql'); decl, body = t.split('--@BODY\n', 1); decl = decl.replace('--@DECL\n', '')
body = body.replace('--@APPLY:01\n', ap + '\n').replace('--@UNDO:01\n', '  -- ===== undo 01 =====\n' + un + '\n')
tally = """  select count(*) filter (where c.ok), count(*) filter (where c.ok is not true),
         coalesce(string_agg(c.name || ' [got: ' || coalesce(c.got, 'null') || ']', ' ; ' order by c.i) filter (where c.ok is not true), '')
    into q_pass, q_fail, q_fails from pg_temp.q_chk c;
  raise exception 'RESULT: % pass, % fail% %', q_pass, q_fail, case when q_fail > 0 then ' | FAILED: ' || q_fails else '' end, q_notes;
"""
out = ('-- GENERATED by src/mk.py. billing_nov22 test 01 (billing and trial end).\n'
       "-- ONE statement (a DO block). Applies 01 (safe to run twice), exercises it as the app (role authenticated, JWT claims) and as\n"
       "-- Thomas (admin, aal2), undoes it, applies it again, then ALWAYS raises 'RESULT: n pass, m fail ...' so NOTHING is kept\n"
       '-- (throwaway users and companies included). Expect an ERROR whose message starts with RESULT: and says 0 fail.\n'
       'do $T$\ndeclare\n' + decl + 'begin\n' + body + tally + 'end $T$;\n')
open(L + '/block_t01.sql', 'w').write(out); print('built block_t01.sql')
